#!/usr/bin/env python3
"""Write src/duckwm/cmd.py and src/duckwm/_api.py from the generated protobuf module.

Run by scripts/gen after protoc; don't edit the outputs by hand.
"""

import keyword
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PKG = ROOT / "src" / "duckwm"
sys.path.insert(0, str(PKG / "_proto"))  # the pb2 alone: the package may not import yet

import duckwm_pb2 as pb  # noqa: E402
from google.protobuf.descriptor import FieldDescriptor as FD  # noqa: E402

INTS = {
    FD.TYPE_INT32,
    FD.TYPE_INT64,
    FD.TYPE_UINT32,
    FD.TYPE_UINT64,
    FD.TYPE_SINT32,
    FD.TYPE_SINT64,
    FD.TYPE_FIXED32,
    FD.TYPE_FIXED64,
    FD.TYPE_SFIXED32,
    FD.TYPE_SFIXED64,
}
# Fields that also take "#rrggbb".
COLORS = {"color", "bg", "win_bg", "border", "text"}
# Message types with friendlier inputs (see _encode.py).
MESSAGES = {
    "Ref": "RefLike",
    "Callback": "CallbackLike",
    "Value": "Any",
    "Command": "CommandLike",
    "LayoutSpec": "pb.LayoutSpec | list[pb.NodeSpec]",
}
# Client methods written by hand, with signatures of their own.
HAND_WRITTEN = {"bind"}

HEADER = (
    "# Generated by scripts/gen_api.py from duckwm.proto. Do not edit.\n# ruff: noqa\n"
)


def screaming(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).upper()


def short(enum, value: str) -> str:
    """DIR_LEFT -> "left"."""
    return value.removeprefix(screaming(enum.name) + "_").lower()


def repeated(f) -> bool:
    r = getattr(f, "is_repeated", None)
    return r if isinstance(r, bool) else f.label == FD.LABEL_REPEATED


def optional(f) -> bool:
    """proto3 `optional`: a synthetic oneof named after the field."""
    o = f.containing_oneof
    return o is not None and o.name.startswith("_")


def ident(name: str) -> str:
    return name + "_" if keyword.iskeyword(name) else name


def py_type(f) -> str:
    if f.type == FD.TYPE_MESSAGE:
        t = MESSAGES.get(
            f.message_type.name, f"pb.{f.message_type.name} | dict[str, Any]"
        )
    elif f.type == FD.TYPE_ENUM:
        names = ", ".join(repr(short(f.enum_type, v.name)) for v in f.enum_type.values)
        t = f"Literal[{names}] | int"
    elif f.type == FD.TYPE_STRING:
        t = "str"
    elif f.type == FD.TYPE_BOOL:
        t = "bool"
    elif f.type in (FD.TYPE_DOUBLE, FD.TYPE_FLOAT):
        t = "float"
    elif f.type in INTS:
        t = "int | str" if f.name in COLORS else "int"
    else:
        t = "Any"
    return f"Sequence[{t}]" if repeated(f) else t


def signature(msg) -> tuple[list[str], list[str], list[str]]:
    """A command's parameters, the arguments passing them on, and its Cmd entries."""
    fields = sorted(msg.fields, key=lambda f: f.number)
    # A lone list of strings (spawn, exec_once) reads better as varargs.
    if len(fields) == 1 and repeated(fields[0]) and fields[0].type == FD.TYPE_STRING:
        f = fields[0]
        n = ident(f.name)
        return [f"*{n}: str"], [f"*{n}"], [f"{f.name!r}: list({n})"]
    req = [f for f in fields if not optional(f)]
    opt = [f for f in fields if optional(f)]
    params = [f"{ident(f.name)}: {py_type(f)}" for f in req]
    params += [f"{ident(f.name)}: {py_type(f)} | None = None" for f in opt]
    args = [ident(f.name) for f in req + opt]
    entries = [f"{f.name!r}: {ident(f.name)}" for f in req + opt]
    return params, args, entries


def main() -> None:
    commands = sorted(pb.Command.DESCRIPTOR.fields, key=lambda f: f.number)
    imports = [
        "from collections.abc import Sequence",
        "from typing import Any, Literal",
        "",
        "from ._encode import CallbackLike, Cmd, CommandLike, RefLike",
        "from ._proto import duckwm_pb2 as pb",
    ]

    cmd = [
        HEADER,
        '"""Every duckwm command, as a value: run it, bind it, batch it, or return it from a callback."""',
        "",
        *imports,
        "",
    ]
    api = [
        HEADER,
        '"""Every duckwm command as a Client method: runs now, returns its result."""',
        "",
        *imports,
        "from . import cmd",
        "",
        "",
        "class Api:",
        '    """Mixed into Client, which provides run()."""',
        "",
        "    def run(self, *cmds: CommandLike) -> list[Any]:",
        "        raise NotImplementedError",
        "",
    ]

    for f in commands:
        name = f.name
        params, args, entries = signature(f.message_type)
        cmd += [
            "",
            f"def {name}({', '.join(params)}) -> Cmd:",
            f"    return Cmd({name!r}, {{{', '.join(entries)}}})",
            "",
        ]
        if name not in HAND_WRITTEN:
            api += [
                f"    def {name}({', '.join(['self', *params])}) -> Any:",
                f"        return self.run(cmd.{name}({', '.join(args)}))[0]",
                "",
            ]

    (PKG / "cmd.py").write_text("\n".join(cmd))
    (PKG / "_api.py").write_text("\n".join(api))
    print(f"generated {len(commands)} commands")


if __name__ == "__main__":
    main()
